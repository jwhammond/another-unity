import { mkdir, mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { runLift, worldList } from './cli';
import { writeMiniRaw } from './testing/mini';

const temps: string[] = [];
afterEach(async () => {
  await Promise.all(temps.splice(0).map(dir => rm(dir, { recursive: true, force: true })));
});

async function setup(edit?: (files: Record<string, unknown>) => void) {
  const raw = await mkdtemp(join(tmpdir(), 'lift-raw-'));
  const out = await mkdtemp(join(tmpdir(), 'lift-out-'));
  temps.push(raw, out);
  await writeMiniRaw(raw, edit);
  await mkdir(join(out, 'overrides'), { recursive: true });
  await mkdir(join(out, 'hooks/ported'), { recursive: true });
  await writeFile(join(out, 'overrides/notes.txt'), 'hand-written\n');
  await writeFile(join(out, 'hooks/register.ts'), '// hand-written\n');
  return { raw, out };
}

async function run(argv: string[]) {
  const lines: string[] = [];
  const code = await runLift(argv, line => lines.push(line));
  return { code, lines };
}

describe('the lift command', () => {
  it('reads worlds as lists, all-away as every away mission, without repeats (M3 Decision 1)', () => {
    expect(worldList(['all-away'])).toEqual([2, 3, 4, 5, 6, 7]);
    expect(worldList(['horst3,2', '7', 'all-away'])).toEqual([7, 2, 3, 4, 5, 6]);
    expect(worldList(['moon'])).toBeUndefined();
  });

  it('refuses an empty list segment instead of reading it as world 0', async () => {
    expect(worldList(['2,,3'])).toBeUndefined();
    expect(worldList(['2,'])).toBeUndefined();
    expect(worldList([''])).toBeUndefined();
    const { raw, out } = await setup();
    const bad = await run(['--raw', raw, '--out', out, '--world', '2,,3', '--dry-run']);
    expect(bad.code).toBe(2);
  });

  it('starts in --start, which must be one of the worlds lifted', async () => {
    const { raw, out } = await setup();
    const ok = await run(['--raw', raw, '--out', out, '--world', 'all-away', '--start', 'horst3', '--dry-run']);
    expect(ok.code).toBe(0);
    expect(ok.lines.some(l => l.startsWith('allanor: 0 objects'))).toBe(true);
    // (without --start, the first mission of the original's order: Horst III, R7)
    const first = await run(['--raw', raw, '--out', out, '--world', 'all-away', '--dry-run']);
    expect(first.code).toBe(0);
    const none = await run(['--raw', raw, '--out', out, '--world', 'allanor', '--dry-run']);
    expect(none.code).toBe(1);
    expect(none.lines).toContain('error: lift: no located screen in allanor, so there is nowhere to start');
    const bad = await run(['--raw', raw, '--out', out, '--world', 'horst3', '--start', 'allanor']);
    expect(bad.code).toBe(2);
    expect(bad.lines[0]).toBe('--start allanor is not one of the worlds lifted');
  });

  it('writes the content package, and a second run changes nothing', async () => {
    const { raw, out } = await setup();
    const first = await run(['--raw', raw, '--out', out, '--world', 'horst3']);
    expect(first.code).toBe(0);
    expect(first.lines).toContain('horst3: 4 objects, 0 stubs, 1 conversations, 3 screens, 1 hooks (0 ported), 0 errors');
    const rubble = await readFile(join(out, 'objects/horst3/s01/rubble.yaml'), 'utf8');
    expect(rubble.startsWith('# Generated by tools/lift from o_070103.')).toBe(true);
    const second = await run(['--raw', raw, '--out', out, '--world', '7']);
    expect(second.code).toBe(0);
    expect(second.lines).toContain('wrote 0 files, 42 unchanged, removed 0');
    expect(await readFile(join(out, 'objects/horst3/s01/rubble.yaml'), 'utf8')).toBe(rubble);
  });

  it('removes a generated file whose object is gone, and never touches hand-written files', async () => {
    const { raw, out } = await setup();
    await run(['--raw', raw, '--out', out, '--world', 'horst3']);
    await rm(raw, { recursive: true });
    await writeMiniRaw(raw, files => {
      delete files['objects/o_070104.json'];
      const s = files['screens/s_0701.json'] as { objects: string[] };
      s.objects = s.objects.filter(id => id !== '070104');
    });
    const dry = await run(['--raw', raw, '--out', out, '--world', 'horst3', '--dry-run']);
    expect(dry.lines).toContain('dry run: would write 5 files, 36 unchanged, remove 1');
    expect(await readFile(join(out, 'objects/horst3/s01/door.yaml'), 'utf8')).toMatch(/^# Generated by tools\/lift/);
    const { code, lines } = await run(['--raw', raw, '--out', out, '--world', 'horst3']);
    expect(code).toBe(0);
    // (the door's file goes; its screen, room, ids, coords and coverage change; nothing else does)
    expect(lines).toContain('wrote 5 files, 36 unchanged, removed 1');
    await expect(readFile(join(out, 'objects/horst3/s01/door.yaml'), 'utf8')).rejects.toThrow(/ENOENT/);
    expect(await readFile(join(out, 'overrides/notes.txt'), 'utf8')).toBe('hand-written\n');
    expect(await readFile(join(out, 'hooks/register.ts'), 'utf8')).toBe('// hand-written\n');
  });

  it('fails without writing anything when the lift has errors', async () => {
    const { raw, out } = await setup();
    await mkdir(join(out, 'overrides/objects'), { recursive: true });
    await writeFile(join(out, 'overrides/objects/gone.yaml'), 'id: horst3.gone\n');
    const { code, lines } = await run(['--raw', raw, '--out', out, '--world', 'horst3']);
    expect(code).toBe(1);
    expect(lines).toContain('error: overrides/objects/gone.yaml: no generated object "horst3.gone" to override');
    expect((await readdir(out)).sort()).toEqual(['hooks', 'overrides']);
    expect(await readFile(join(out, 'overrides/notes.txt'), 'utf8')).toBe('hand-written\n');
    expect(await readFile(join(out, 'hooks/register.ts'), 'utf8')).toBe('// hand-written\n');
  });

  it('writes nothing in a dry run, and explains its arguments', async () => {
    const { raw, out } = await setup();
    const dry = await run(['--raw', raw, '--out', out, '--world', 'horst3', '--dry-run']);
    expect(dry.code).toBe(0);
    expect(dry.lines).toContain('dry run: would write 42 files, 0 unchanged, remove 0');
    expect((await readdir(out)).sort()).toEqual(['hooks', 'overrides']);
    const bad = await run(['--world', 'horst3']);
    expect(bad.code).toBe(2);
    expect(bad.lines[0]).toBe('usage: lift --raw <export dir> --world <slug, number, list or all-away>... [--start <world>] [--out games/unity] [--images <dir>] [--audio <dir>] [--dry-run]');
  });
});
