import { describe, expect, it } from 'vitest';
import { hookCall, hooksModule } from './hooks';
import { testCtx } from './testing/ctx';

describe('hook stubs', () => {
  it('turns each special into a call, and records who uses it', () => {
    const ctx = testCtx();
    const detail = 'GeneralBlock command type 5, which ScummVM only warns about';
    const source = 'engines/unity/object.cpp:1805 (GeneralBlock::execute)';
    expect(hookCall(ctx, 'unity.general.g5', { value: 12 }, detail, source, 'o_070100#/use_entries/0/3'))
      .toEqual({ call: { hook: 'unity.general.g5', args: { value: 12 } } });
    hookCall(ctx, 'unity.general.g5', { value: 13 }, detail, source, 'o_070104#/use_entries/0/1');
    expect(ctx.hooks.list()).toEqual([
      { name: 'unity.general.g5', detail, source, usedBy: ['o_070100#/use_entries/0/3', 'o_070104#/use_entries/0/1'] },
    ]);
  });

  it('writes a module of stubs that throw NotPorted, or the ported hook if there is one', () => {
    const stubs = [
      { name: 'unity.command.c9', detail: 'CommandBlock command 9', source: 'engines/unity/object.cpp:1630', usedBy: ['o_070100#/use_entries/0/0'] },
      { name: 'unity.general.g5', detail: 'GeneralBlock command type 5', source: 'engines/unity/object.cpp:1805', usedBy: ['o_070100#/use_entries/0/3'] },
    ];
    expect(hooksModule(stubs, new Set(['unity.general.g5']))).toBe([
      '// SPDX-License-Identifier: GPL-3.0-or-later',
      '// Generated by tools/lift. Do not edit: to port a hook, add games/unity/hooks/ported/<name>.ts',
      '// exporting `export const hook: Hook`, and run the lifter again.',
      "import { NotPorted, type Hook } from '@another-unity/engine';",
      "import { hook as ported1 } from './ported/unity.general.g5';",
      '',
      'export const hooks: Record<string, Hook> = {',
      '  /**',
      '   * CommandBlock command 9',
      '   * ScummVM: engines/unity/object.cpp:1630',
      '   * Used by: o_070100#/use_entries/0/0',
      '   */',
      "  'unity.command.c9': () => {",
      "    throw new NotPorted('unity.command.c9');",
      '  },',
      '  /**',
      '   * GeneralBlock command type 5',
      '   * ScummVM: engines/unity/object.cpp:1805',
      '   * Used by: o_070100#/use_entries/0/3',
      '   */',
      "  'unity.general.g5': ported1,",
      '};',
      '',
    ].join('\n'));
  });
});
