import type { Effect } from '@another-unity/engine';
import type { LiftCtx } from './context';

export interface HookStub {
  name: string;
  /** What the original does here, in a sentence. */
  detail: string;
  /** The ScummVM code that implements (or ignores) it. */
  source: string;
  /** Every IR pointer that calls it. */
  usedBy: string[];
}

export class HookStubs {
  private readonly stubs = new Map<string, HookStub>();

  add(name: string, detail: string, source: string, where: string): void {
    const stub = this.stubs.get(name);
    if (stub) stub.usedBy.push(where);
    else this.stubs.set(name, { name, detail, source, usedBy: [where] });
  }

  list(): HookStub[] {
    return [...this.stubs.values()].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  }
}

/** A `call` to a hook for behavior the content model can't express; the hook gets a generated stub. */
export function hookCall(ctx: LiftCtx, name: string, args: Record<string, unknown>, detail: string, source: string, where: string): Effect {
  ctx.hooks.add(name, detail, source, where);
  return { call: { hook: name, ...(Object.keys(args).length > 0 ? { args } : {}) } };
}

/** games/unity/hooks/generated.ts: each stub throws NotPorted, unless hooks/ported/<name>.ts exists. */
export function hooksModule(stubs: HookStub[], ported: ReadonlySet<string>): string {
  const lines = [
    '// SPDX-License-Identifier: GPL-3.0-or-later',
    '// Generated by tools/lift. Do not edit: to port a hook, add games/unity/hooks/ported/<name>.ts',
    '// exporting `export const hook: Hook`, and run the lifter again.',
    "import { NotPorted, type Hook } from '@another-unity/engine';",
  ];
  stubs.forEach((s, i) => {
    if (ported.has(s.name)) lines.push(`import { hook as ported${i} } from './ported/${s.name}';`);
  });
  lines.push('', 'export const hooks: Record<string, Hook> = {');
  stubs.forEach((s, i) => {
    lines.push('  /**', `   * ${s.detail}`, `   * ScummVM: ${s.source}`, `   * Used by: ${s.usedBy.join(', ')}`, '   */');
    if (ported.has(s.name)) lines.push(`  '${s.name}': ported${i},`);
    else lines.push(`  '${s.name}': () => {`, `    throw new NotPorted('${s.name}');`, '  },');
  });
  lines.push('};', '');
  return lines.join('\n');
}
