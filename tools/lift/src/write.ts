import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, relative, sep } from 'node:path';
import { parseDocument } from 'yaml';
import { YAML_HEADER } from './lift';

/** Directories the lifter never looks in: hand edits, ported hooks, and other tools' output. */
const NOT_OURS = ['overrides/', 'hooks/ported/', 'audio/', 'movies/', 'models/', 'art/'];

/** A re-lift keeps the `art` key of the presentation.yaml it replaces (R8): tools/art publish put it there, not the lifter. */
export function carryArt(previous: string | undefined, next: string): string {
  if (previous === undefined) return next;
  const art = parseDocument(previous).get('art', true);
  if (art === undefined || art === null) return next;
  const doc = parseDocument(next);
  doc.set('art', art);
  return String(doc);
}

export function isGenerated(text: string): boolean {
  const head = text.slice(0, 200);
  return head.startsWith(YAML_HEADER) || head.startsWith('// Generated by tools/lift') || head.includes('"generated": "tools/lift"');
}

async function listFiles(dir: string): Promise<string[]> {
  let entries;
  try {
    entries = await readdir(dir, { recursive: true, withFileTypes: true });
  } catch {
    return [];
  }
  return entries.filter(e => e.isFile())
    .map(e => relative(dir, join(e.parentPath, e.name)).split(sep).join('/'))
    .filter(rel => !NOT_OURS.some(d => rel.startsWith(d)))
    .sort();
}

export interface OutputPlan {
  /** Files that are new or changed, in the lift's order. */
  writes: string[];
  unchanged: number;
  /** Generated files the lift no longer produces. */
  removals: string[];
}

/** What writing the lift's files would do, without changing anything. */
export async function planOutput(outDir: string, files: Map<string, string>): Promise<OutputPlan> {
  const removals: string[] = [];
  for (const rel of await listFiles(outDir)) {
    if (files.has(rel)) continue;
    if (isGenerated(await readFile(join(outDir, rel), 'utf8'))) removals.push(rel);
  }
  // (the art key is the art tool's, not the lift's)
  const presentation = files.get('presentation.yaml');
  if (presentation !== undefined) {
    files.set('presentation.yaml', carryArt(await readFile(join(outDir, 'presentation.yaml'), 'utf8').catch(() => undefined), presentation));
  }
  const writes: string[] = [];
  let unchanged = 0;
  for (const [rel, text] of files) {
    const old = await readFile(join(outDir, rel), 'utf8').catch(() => undefined);
    if (old === text) unchanged++;
    else writes.push(rel);
  }
  return { writes, unchanged, removals };
}

/** Carries out a plan: removes its stale files and writes its new or changed ones. */
export async function applyOutput(outDir: string, files: Map<string, string>, plan: OutputPlan): Promise<void> {
  for (const rel of plan.removals) await rm(join(outDir, rel));
  for (const rel of plan.writes) {
    const path = join(outDir, rel);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, files.get(rel)!);
  }
}

/** Writes changed files, and removes generated files the lift no longer produces. */
export async function writeOutput(outDir: string, files: Map<string, string>): Promise<{ written: string[]; unchanged: number; removed: string[] }> {
  const plan = await planOutput(outDir, files);
  await applyOutput(outDir, files, plan);
  return { written: plan.writes, unchanged: plan.unchanged, removed: plan.removals };
}
