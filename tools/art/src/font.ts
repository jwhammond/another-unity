/** The label's size in pixels at `scale` (a glyph is 5x7 plus a one-column gap). */
export function textSize(text: string, scale: number): [number, number] {
  return [Math.max(0, text.length * 6 - 1) * scale, 7 * scale];
}

/** Draws `text` with its top-left at (x, y) on a padded box (`bg`, or none), clipped to the image. */
export function drawText(img: Rgba, text: string, x: number, y: number, opts: { scale?: number; fg?: [number, number, number]; bg?: [number, number, number, number] } = {}): void {
  const s = opts.scale ?? 2;
  const fg = opts.fg ?? [255, 255, 255];
  const put = (px: number, py: number, rgb: readonly number[], a: number): void => {
    if (px < 0 || py < 0 || px >= img.width || py >= img.height) return;
    const i = (py * img.width + px) * 4;
    for (let c = 0; c < 3; c++) img.data[i + c] = Math.round(img.data[i + c]! * (1 - a) + rgb[c]! * a);
  };
  if (opts.bg) {
    const [w, h] = textSize(text, s);
    for (let py = y - s; py < y + h + s; py++) for (let px = x - s; px < x + w + s; px++) put(px, py, opts.bg, opts.bg[3] / 255);
  }
  [...text.toUpperCase()].forEach((ch, n) => {
    const rows = (GLYPHS[ch] ?? GLYPHS['?']!).split(' ');
    rows.forEach((row, gy) => {
      for (let gx = 0; gx < 5; gx++) {
        if (row[gx] !== '1') continue;
        for (let dy = 0; dy < s; dy++) for (let dx = 0; dx < s; dx++) put(x + (n * 6 + gx) * s + dx, y + gy * s + dy, fg, 1);
      }
    });
  });
}
