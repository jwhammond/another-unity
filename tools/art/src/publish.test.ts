function grey(v: number): Rgba {
  const data = new Uint8Array(16 * 16 * 4);
  for (let i = 0; i < 256; i++) data.set([v, v, v, 255], i * 4);
  return { width: 16, height: 16, data };
}
/** A stand-in for cwebp and dwebp: the "WebP" is the PNG's bytes, and decode adds `drift` levels. */
const codec = (drift: number): Required<Pick<PublishDeps, 'encode' | 'decode'>> => ({
  encode: (png, out) => copyFile(png, out),
  decode: async webp => {
    const img = decodePng(new Uint8Array(await readFile(webp)));
    for (let i = 0; i < img.data.length; i += 4) for (let k = 0; k < 3; k++) img.data[i + k] = img.data[i + k]! + drift;
    return img;
  },
});
async function setup(): Promise<{ run: string; game: string; meta: RunMeta }> {
  tmp = await mkdtemp(join(tmpdir(), 'publish-'));
  const run = join(tmp, 'run');
  const game = join(tmp, 'game');
  await mkdir(run);
  await mkdir(game);
  await writeFile(join(run, 'plate.png'), encodePng(grey(100)));
  await writeFile(join(run, 'depth.png'), 'D');
  const out = (name: string) => ({ file: join(run, `${name}.png`), sha256: 'x', width: 16, height: 16 });
  const meta = { outputs: { plate: out('plate'), depth: out('depth'), upscaled: out('plate') }, checks: { align: { ok: true } } } as unknown as RunMeta;
  return { run, game, meta };
}

