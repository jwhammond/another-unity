    await expect(readFile(join(game, 'presentation.yaml'), 'utf8')).rejects.toThrow();
    await publishRoom(game, 'w.s01', { dir: run, meta }, { encode: (png, out) => copyFile(png, out), decode: async () => crosses(0), align });
