describe('publishShipViews', () => {
  it('writes each hail frame as art/ship/view/<stem>.webp and refuses a stem that is not one', async () => {
    const { run, game } = await setup();
    await writeFile(join(run, 'a.png'), encodePng(grey(9)));
    const files = await publishShipViews(game, [{ stem: 'viewfere', png: join(run, 'a.png') }, { stem: 'vwspace', png: join(run, 'a.png') }], { encode: (png, out) => copyFile(png, out) });
    expect(files).toEqual(['art/ship/view/viewfere.webp', 'art/ship/view/vwspace.webp']);
    expect(existsSync(join(game, 'art/ship/view/viewfere.webp'))).toBe(true);
    await expect(publishShipViews(game, [{ stem: '../x', png: join(run, 'a.png') }])).rejects.toThrow(/sprite stem/);
  });

  it('a 3-frame sprite publishes a 3-cell sheet, recorded as art.ship.viewscreen.views[stem] with its own delays', async () => {
    const { run, game } = await setup();
    await writeFile(join(game, 'presentation.yaml'), 'art:\n  ship:\n    viewscreen:\n      plate: art/ship/viewscreen/plate.webp\n');
    await writeFile(join(run, 'a.png'), encodePng(grey(9)));
    // (a synthetic sprite: animation 0 is three 2x1 frames, each a wait of 16 ticks, and a jump to itself)
    const u32 = (n: number): number[] => [n & 255, (n >> 8) & 255, (n >> 16) & 255, (n >>> 24) & 255];
    const block = (type: string, body: number[]): number[] => [...[...type].map(c => c.charCodeAt(0)), ...u32(body.length + 8), ...body];
    const frame = (a: number, b: number): number[] => {
      const bits = [a, b].map(c => '01' + c.toString(2).padStart(8, '0')).join('');
      const bytes: number[] = [];
      for (let i = 0; i < bits.length; i += 8) bytes.push(parseInt(bits.slice(i, i + 8).padEnd(8, '0'), 2));
      return block('PMOC', [...u32(2), ...u32(1), 0x0d, 0, 2, 0, ...bytes]);
    };
    const blocks = [frame(1, 2), block('EMIT', u32(16 * 16)), frame(3, 4), block('EMIT', u32(16 * 16)), frame(5, 6), block('EMIT', u32(16 * 32)), block('PMUJ', u32(0))];
    const body = [...u32(1), ...u32(16), ...blocks.flat()];
    const spr = new Uint8Array(block('TRPS', [...u32(0x1000), ...block('TSIL', body)]));
    const palette = new Uint8Array(256 * 3).map((_, i) => i % 256);
    const sheets = viewStrips(readScript(spr), palette);
    const files = await publishShipViews(game, [{ stem: 'vwtest', png: join(run, 'a.png'), sheets }], { encode: (png, out) => copyFile(png, out) });
    expect(files).toEqual(['art/ship/view/vwtest.webp', 'art/ship/view/vwtest.0.0.webp']);
    // (one page: the three 2x1 cells, a pixel of gutter between them)
    const sheet = decodePng(new Uint8Array(await readFile(join(game, 'art/ship/view/vwtest.0.0.webp'))));
    const doc = parse(await readFile(join(game, 'presentation.yaml'), 'utf8'));
    const view = doc.art.ship.viewscreen.views.vwtest['0'];
    expect(view).toMatchObject({ images: ['art/ship/view/vwtest.0.0.webp'], pages: [[sheet.width, sheet.height]], frames: 3, scale: 1, cell: [2, 1], loop: true });
    expect(view.cells).toHaveLength(3);
    expect(view.cells.map((c: number[]) => [c[0], c[3], c[4]])).toEqual([[0, 2, 1], [0, 2, 1], [0, 2, 1]]);
    // (the sprite's waits: 16 and 32 ticks of the original's sprite clock)
    expect(view.delays).toEqual([waitMillis(256), waitMillis(256), waitMillis(512)]);
    // the plate stays, and the views parse as the engine reads them
    expect(doc.art.ship.viewscreen.plate).toBe('art/ship/viewscreen/plate.webp');
    expect(parsePresentation(await readFile(join(game, 'presentation.yaml'), 'utf8')).art.ship.viewscreen?.views?.vwtest?.['0']?.frames).toBe(3);
    // a publish with no sheets leaves none
    await publishShipViews(game, [{ stem: 'vwtest', png: join(run, 'a.png') }], { encode: (png, out) => copyFile(png, out) });
    expect(parse(await readFile(join(game, 'presentation.yaml'), 'utf8')).art.ship.viewscreen.views).toBeUndefined();
    expect(existsSync(join(game, 'art/ship/view/vwtest.0.0.webp'))).toBe(false);
  });

  it('a view whose frames exceed 4096 px packs into pages of at most 4096 on each side', async () => {
    const { run, game } = await setup();
    await writeFile(join(game, 'presentation.yaml'), 'art:\n  ship:\n    viewscreen:\n      plate: art/ship/viewscreen/plate.webp\n');
    await writeFile(join(run, 'a.png'), encodePng(grey(9)));
    // (a synthetic script: three 2100x2100 frames of one colour each, a wait after each, round again; together 6300 px across)
    const side = 2100;
    const frame = (c: number) => ({ type: 'sprite' as const, width: side, height: side, indices: new Uint8Array(side * side).fill(c) });
    const script = { anims: [0], entries: [frame(1), { type: 'wait' as const, wait: 256 }, frame(2), { type: 'wait' as const, wait: 256 }, frame(3), { type: 'wait' as const, wait: 256 }, { type: 'jump' as const, target: 0 }] };
    const palette = new Uint8Array(256 * 3).map((_, i) => i % 256);
    const sheets = viewStrips(script, palette);
    const strip = sheets.get(0)!;
    expect(strip.pages.length).toBeGreaterThan(1);
    for (const p of strip.pages) expect(Math.max(p.width, p.height)).toBeLessThanOrEqual(4096);
    const files = await publishShipViews(game, [{ stem: 'vwbig', png: join(run, 'a.png'), sheets }], { encode: (png, out) => copyFile(png, out) });
    const view = parse(await readFile(join(game, 'presentation.yaml'), 'utf8')).art.ship.viewscreen.views.vwbig['0'];
    expect(view.images).toEqual(strip.pages.map((_, n) => `art/ship/view/vwbig.0.${n}.webp`));
    expect(files.slice(1)).toEqual(view.images);
    for (const [n, image] of view.images.entries()) {
      const page = decodePng(new Uint8Array(await readFile(join(game, image))));
      expect([page.width, page.height]).toEqual(view.pages[n]);
      expect(Math.max(page.width, page.height)).toBeLessThanOrEqual(4096);
    }
    // every frame's cell lies whole in a page, at the cell's size
    for (const [p, x, y, w, h] of view.cells as number[][]) {
      expect([w, h]).toEqual([side, side]);
      expect(x + w).toBeLessThanOrEqual(view.pages[p][0]);
      expect(y + h).toBeLessThanOrEqual(view.pages[p][1]);
    }
  });
});

describe('the half-resolution plate', () => {
  it('is half the width and height, never under one pixel', () => {
    expect(halfSize(2560, 1920)).toEqual([1280, 960]);
    expect(halfSize(1, 3)).toEqual([1, 1]);
  });

  it('is encoded with the half size by default, beside the plate, as the real encoder is asked (cwebp -resize)', async () => {
    const { cwebpArgs } = await import('./webp');
    const args = cwebpArgs('in.png', 'out.webp', { quality: 90, resize: halfSize(2560, 1920) });
    expect(args.slice(args.indexOf('-resize'), args.indexOf('-resize') + 3)).toEqual(['-resize', '1280', '960']);
    expect(cwebpArgs('in.png', 'out.webp', { quality: 90 })).not.toContain('-resize');
  });

  it('is written beside a plate published without one, and left alone once it is newer than the plate', async () => {
    tmp = await mkdtemp(join(tmpdir(), 'half-'));
    await mkdir(join(tmp, 'art/rooms/w/s01'), { recursive: true });
    await mkdir(join(tmp, 'art/ship/bridge'), { recursive: true });
    // (a lossy WebP header: "RIFF", size, "WEBP", "VP8 ", chunk size, frame tag, start code, then the 14-bit width and height)
    const header = (w: number, h: number) => {
      const b = new Uint8Array(40);
      b.set([...'RIFF'].map(c => c.charCodeAt(0)), 0);
      b.set([...'WEBP'].map(c => c.charCodeAt(0)), 8);
      b.set([...'VP8 '].map(c => c.charCodeAt(0)), 12);
      b.set([w & 255, w >> 8, h & 255, h >> 8], 26);
      return b;
    };
    await writeFile(join(tmp, 'art/rooms/w/s01/plate.webp'), header(2560, 1920));
    await writeFile(join(tmp, 'art/ship/bridge/plate.webp'), header(2560, 1920));
    const sizes: [number, number][] = [];
    const encode = async (webp: string, out: string, size: [number, number]) => { sizes.push(size); await copyFile(webp, out); };
    const written = await halfPublishedPlates(tmp, { encode });
    expect(written.sort()).toEqual(['art/rooms/w/s01/plate.half.webp', 'art/ship/bridge/plate.half.webp']);
    expect(sizes).toEqual([[1280, 960], [1280, 960]]);
    expect(await halfPublishedPlates(tmp, { encode })).toEqual([]);
  });
});
